function renderQuestions(containerId, questions) {
  const container = document.getElementById(containerId);
  if (!container) return;
  container.innerHTML = questions.map((item, i) => `
    <div class="test-question">
      <h3>${i + 1}. ${item.q}</h3>
      <div class="test-options">
        ${item.opts.map((o, j) => `<button class="test-option" data-correct="${j === item.c}">${String.fromCharCode(65 + j)}) ${o}</button>`).join('')}
      </div>
    </div>
  `).join('');
}

function renderOpenQuestions(containerId, questions) {
  const container = document.getElementById(containerId);
  if (!container) return;
  container.innerHTML = questions.map((item, i) => `
    <div class="open-question">
      <label class="open-question__label" for="suraq_${i}">
        <span class="open-question__num">${i + 1}</span>
        ${item.q}
      </label>
      <textarea
        id="suraq_${i}"
        class="open-question__input"
        rows="5"
        placeholder="Жауабыңызды жазыңыз..."
        data-suraq-index="${i}"
      ></textarea>
    </div>
  `).join('');
}
